'use strict';
const assert=require('node:assert/strict');
const office=require('../src/assets/sunrise-office-export.js');
const text=(str,x,y,width=50)=>({str,width,dir:'ltr',transform:[12,0,0,12,x,y]});
const rules={horizontal:[100,200,300].map(at=>({at,from:0,to:200})),vertical:[{at:0,from:100,to:300},{at:200,from:100,to:300},{at:100,from:100,to:200}]};
const page={width:400,height:600,rotation:0,items:[text('병합 셀',10,250),text('=SUM(1)',10,150),text('둘째',110,150),text('표 밖',10,400)]};
const grid=office.gridModel(page,rules);
assert.equal(grid.cells.length,3);assert(grid.cells.some(c=>c.c0===0&&c.c1===1&&c.r0===0&&c.r1===0));
const excel=Buffer.from(office.xlsxGrids([page],[rules])).toString('utf8');
assert(excel.includes('<mergeCell ref="A1:B1"/>'));assert(excel.includes('=SUM(1)'));assert(!excel.includes('<f>'));
assert(excel.includes('표 밖'));assert(excel.includes('t="inlineStr"'));
const word=Buffer.from(office.docxGrids([page],[rules])).toString('utf8');
assert(word.includes('<w:gridSpan w:val="2"/>'));assert(word.includes('병합 셀'));assert(word.includes('표 밖'));
assert.throws(()=>office.gridModel(page,{horizontal:[],vertical:[]}),/격자/);
const tooWide={...page,items:[text('crosses boundary',50,150,120)]};
assert.throws(()=>office.gridModel(tooWide,rules),/경계/);
const png=Uint8Array.from(Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jY3cAAAAASUVORK5CYII=','base64'));
const visual=Buffer.from(office.docxVisual([{width:595,height:842,png}]));
assert(visual.includes(Buffer.from('word/media/page1.png')));assert(visual.includes(Buffer.from('wp:anchor')));
assert(visual.includes(Buffer.from(png)),'PNG bytes must be stored without text encoding');
console.log('R33 Office grid and visual package regressions passed');
