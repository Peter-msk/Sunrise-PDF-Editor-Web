const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const PDFLib = require('../dist/assets/pdf-lib/pdf-lib.min.js');
const source = fs.readFileSync('src/editor/index.html', 'utf8');
const start = source.indexOf('    async function inspectSavedPdf(');
const end = source.indexOf('    function openSavedPdfCheckModal(', start);
assert.ok(start >= 0 && end > start);
const context = vm.createContext({window: {PDFLib}, validatePdfByteLength: n => { if (!n || n > 50 * 1024 * 1024) throw Error('invalid size'); }});
vm.runInContext(source.slice(start, end), context);
const geometryStart = source.indexOf('    function verifyPdfPageGeometry(');
const geometryEnd = source.indexOf('    // Batch output must preserve structural', geometryStart);
assert.ok(geometryStart >= 0 && geometryEnd > geometryStart);
vm.runInContext(source.slice(geometryStart, geometryEnd), context);
(async () => {
  const doc = await PDFLib.PDFDocument.create();
  doc.addPage([100, 200]);
  doc.addPage([100, 200]).setRotation(PDFLib.degrees(90));
  doc.addPage([100, 100]);
  const bytes = await doc.save();
  const result = await context.inspectSavedPdf(bytes);
  assert.equal(result.bytes, bytes.byteLength);
  assert.equal(result.pageCount, 3);
  assert.equal(result.orientation.portrait, 1);
  assert.equal(result.orientation.landscape, 1);
  assert.equal(result.orientation.square, 1);
  await assert.rejects(context.inspectSavedPdf(new Uint8Array([1, 2, 3])));
  await assert.rejects(context.inspectSavedPdf(new Uint8Array(0)));
  const originalCopy = Uint8Array.from(bytes);
  await assert.doesNotReject(context.verifySavedPdfBytes(bytes, bytes));
  const changedCount = await PDFLib.PDFDocument.load(bytes);
  changedCount.removePage(2);
  await assert.rejects(context.verifySavedPdfBytes(bytes, await changedCount.save()), /페이지 수/);
  const changedRotation = await PDFLib.PDFDocument.load(bytes);
  changedRotation.getPage(1).setRotation(PDFLib.degrees(180));
  await assert.rejects(context.verifySavedPdfBytes(bytes, await changedRotation.save()), /회전/);
  const changedCrop = await PDFLib.PDFDocument.load(bytes);
  changedCrop.getPage(0).setCropBox(4, 0, 96, 200);
  await assert.rejects(context.verifySavedPdfBytes(bytes, await changedCrop.save()), /크기·좌표/);
  const changedTrim = await PDFLib.PDFDocument.load(bytes);
  changedTrim.getPage(0).setTrimBox(0, 5, 100, 195);
  await assert.rejects(context.verifySavedPdfBytes(bytes, await changedTrim.save()), /getTrimBox/);
  await assert.rejects(context.verifySavedPdfBytes(bytes, new Uint8Array([1, 2, 3])));
  assert.deepEqual(bytes, originalCopy, 'Save verification must not change source bytes');
  console.log('PASS: saved PDF preflight and download gate block missing pages, rotation/box damage and corrupt bytes');
})().catch(error => { console.error(error); process.exitCode = 1; });
