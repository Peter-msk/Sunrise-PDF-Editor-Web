const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const lib=require('../dist/assets/pdf-lib/pdf-lib.min.js');
const pages=require('../src/assets/sunrise-batch-pages.js');
const name=lib.PDFName.of;
(async()=>{
 const first=await lib.PDFDocument.create();
 first.setTitle('First sample');
 first.addPage([420,595]).drawText('Report introduction',{x:35,y:550});
 const rotated=first.addPage([612,792]);rotated.setRotation(lib.degrees(90));
 rotated.drawText('Appendix',{x:35,y:700});
 first.addPage([500,700]).drawText('Appendix second page',{x:35,y:650});
 const second=await lib.PDFDocument.create();
 second.addPage([320,480]).drawText('Second file',{x:30,y:420});
 const firstBytes=await first.save(),secondBytes=await second.save(),unchanged=Uint8Array.from(firstBytes);
 const file=(name,bytes)=>({name,size:bytes.byteLength,bytes});
 const original=[file('첫번째.pdf',firstBytes),file('second.pdf',secondBytes)];
 const readFile=async f=>f.bytes;
 const options={PDFLib:lib,readFile};
 const results=[],errors=[],progress=[];
 const handlers={cancelled:()=>false,progress:(...x)=>progress.push(x),result:x=>results.push(x),error:x=>errors.push(x)};
 await pages.process(original,{mode:'split',pagesPerFile:2},handlers,options);
 if(errors.length)console.error('Split diagnostics:',errors);
 assert.equal(errors.length,0,'valid documents must split');
 assert.equal(results.length,3,'3-page + 1-page inputs should create three output files');
 assert.deepEqual(results.map(r=>[r.name,r.startPage,r.endPage]),
   [['첫번째.pdf',1,2],['첫번째.pdf',3,3],['second.pdf',1,1]]);
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'sunrise-batch-pages-'));
 try{
  for(const [i,result] of results.entries()){
    const filename=path.join(temp,'split-'+i+'.pdf');
    fs.writeFileSync(filename,result.bytes);
    const reopened=await lib.PDFDocument.load(fs.readFileSync(filename));
    assert.equal(reopened.getPageCount(),result.endPage-result.startPage+1);
    assert.equal(reopened.catalog.get(name('AcroForm')),undefined);
  }
  const firstPart=await lib.PDFDocument.load(results[0].bytes);
  assert.equal(firstPart.getPage(1).getRotation().angle,90);
  assert.equal(firstPart.getPage(1).getMediaBox().width,612);
  results.length=0;errors.length=0;progress.length=0;
  await pages.process(original,{mode:'merge'},handlers,options);
  assert.equal(errors.length,0);assert.equal(results.length,1);
  const mergedFile=path.join(temp,'merged.pdf');
  fs.writeFileSync(mergedFile,results[0].bytes);
  const merged=await lib.PDFDocument.load(fs.readFileSync(mergedFile));
  assert.equal(merged.getPageCount(),4);
  assert.equal(merged.getPage(1).getRotation().angle,90);
  assert.equal(merged.getPage(3).getCropBox().width,320);
  assert.equal(merged.catalog.get(name('AcroForm')),undefined);
 }finally{fs.rmSync(temp,{recursive:true,force:true})}
 assert.deepEqual([...firstBytes],[...unchanged],'source PDF bytes must never mutate');
 const form=await lib.PDFDocument.create();const formPage=form.addPage([400,600]);
 form.getForm().createTextField('client').addToPage(formPage);
 const formFile=file('form.pdf',await form.save());
 results.length=0;errors.length=0;
 await pages.process([formFile,original[1]],{mode:'merge'},handlers,options);
 assert.equal(results.length,0,'merge must be atomic');
 assert.match(errors[0]?.message||'',/AcroForm/);
 results.length=0;errors.length=0;
 await pages.process([formFile,original[1]],{mode:'split',pagesPerFile:1},handlers,options);
 assert.equal(errors.length,1,'form PDF fails individually');
 assert.equal(results.length,1,'valid PDF after rejected form must still split');
 const signed=await lib.PDFDocument.create();signed.addPage();
 signed.catalog.set(name('Perms'),signed.context.obj({}));
 errors.length=0;results.length=0;
 await pages.process([file('signed.pdf',await signed.save())],{mode:'split',pagesPerFile:1},handlers,options);
 assert.match(errors[0]?.message||'',/Perms/);
 const bookmark=await lib.PDFDocument.create();bookmark.addPage();
 bookmark.catalog.set(name('Outlines'),bookmark.context.obj({Type:'Outlines'}));
 errors.length=0;results.length=0;
 await pages.process([file('outline.pdf',await bookmark.save())],{mode:'split',pagesPerFile:1},handlers,options);
 assert.match(errors[0]?.message||'',/Outlines/);
 const annotated=await lib.PDFDocument.create();const annotatedPage=annotated.addPage();
 annotatedPage.node.set(name('Annots'),annotated.context.obj([annotated.context.obj({Type:'Annot',Subtype:'Text'})]));
 errors.length=0;
 await pages.process([file('annotations.pdf',await annotated.save())],{mode:'split',pagesPerFile:1},handlers,options);
 assert.match(errors[0]?.message||'',/Annots/);
 const corrupt=file('corrupt.pdf',Uint8Array.from([1,2,3]));
 errors.length=0;results.length=0;
 await pages.process([corrupt,original[1]],{mode:'merge'},handlers,options);
 assert.equal(results.length,0);assert.equal(errors.length,1);
 await assert.rejects(pages.process([original[0]],{mode:'merge'},handlers,options),/2~5개/);
 await assert.rejects(pages.process(original,{mode:'split',pagesPerFile:0},handlers,options),/1~100/);
 await assert.rejects(pages.process(Array(6).fill(original[0]),{mode:'split',pagesPerFile:1},handlers,options),/1~5개/);
 let cancel=true;results.length=0;
 await pages.process(original,{mode:'merge'},{...handlers,cancelled:()=>cancel},options);
 assert.equal(results.length,0);
 const editor=fs.readFileSync('src/editor/index.html','utf8');
 const build=fs.readFileSync('scripts/build-release.cjs','utf8');
 assert(editor.includes('case "batchPages"'));
 assert(editor.includes('SunriseBatchPages.process('));
 assert(editor.includes('/assets/sunrise-batch-pages.js'));
 assert(build.includes("'sunrise-batch-pages.js'"));
 console.log('PASS: split/merge PDF disk roundtrip; rotation, size and source immutability; safe form/signature/bookmark/annotation rejection; cancellation, atomic merge and UI wiring');
})().catch(e=>{console.error(e);process.exitCode=1});
