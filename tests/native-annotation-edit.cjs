'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const PDFLib=require('../dist/assets/pdf-lib/pdf-lib.min.js');
const html=fs.readFileSync('src/editor/index.html','utf8');
const start=html.indexOf('    function nativeAnnotationHasMarker(');
const end=html.indexOf('    async function openNativeAnnotationsModal(',start);
assert(start>=0 && end>start, 'native annotation mutation routines must be present');
assert(html.includes('id: "manageNativeAnnotations"'), 'Ribbon must expose native annotations');
assert(html.includes('case "manageNativeAnnotations":'), 'Ribbon command must open annotation manager');
// Annotation edits intentionally allow a reduced /Annots count on delete.
// The serialized PDF must still be verified before committing an undo snapshot.
const verified=html.indexOf('await verifySavedPdfBytes(originalBytes,next,{allowAnnotationChanges:true})');
const committed=html.indexOf('saveUndoSnapshot(doc,action==="edit"?"원본 주석 문구 수정":"원본 주석 삭제")');
assert(verified>=0 && committed>verified, 'Annotation-aware PDF structure validation must precede the mutation commit');
const ctx=vm.createContext({window:{PDFLib},Uint8Array,Array,Number,Error});
vm.runInContext(html.slice(start,end),ctx);
const n=PDFLib.PDFName.of;
const fresh=bytes=>PDFLib.PDFDocument.load(bytes,{updateMetadata:false});
const annotation=(pdf,page,subtype,contents,additional={})=>{
 const dict=pdf.context.obj({Type:'Annot',Subtype:subtype,Rect:[30,30,130,50],
   Contents:PDFLib.PDFHexString.fromText(contents),F:4,...additional});
 const ref=pdf.context.register(dict);page.node.addAnnot(ref);return ref;
};
(async()=>{
 const original=await PDFLib.PDFDocument.create(),p0=original.addPage([400,500]),p1=original.addPage([400,500]);
 annotation(original,p0,'Text','초기 한국어 의견');
 annotation(original,p0,'Highlight','검토 필요', {QuadPoints:[30,50,130,50,30,30,130,30],C:[1,1,0]});
 annotation(original,p0,'Square','이 타입은 보호');
 annotation(original,p1,'Text','다음 쪽 의견');
 const raw=await original.save(),savedRaw=Uint8Array.from(raw);
 const doc=await fresh(raw);
 assert.equal(ctx.listNativeAnnotations(doc,0).length,2);
 assert.equal(ctx.listNativeAnnotations(doc,1).length,1);
 assert.equal(ctx.listNativeAnnotations(doc,0)[0].text,'초기 한국어 의견');
 assert.throws(()=>ctx.listNativeAnnotations(doc,-1),/페이지/);
 ctx.updateNativeAnnotation(doc,raw,0,0,'edit','수정된 검토 의견');
 let serialized=await doc.save(),reopen=await fresh(serialized);
 assert.equal(ctx.listNativeAnnotations(reopen,0)[0].text,'수정된 검토 의견');
 assert.equal(ctx.listNativeAnnotations(reopen,0)[1].text,'검토 필요');
 assert.equal(reopen.getPage(0).node.Annots().size(),3);
 const editedHighlight=await fresh(serialized);
 ctx.updateNativeAnnotation(editedHighlight,serialized,0,1,'edit','새로운 강조 설명');
 const marked=await fresh(await editedHighlight.save());
 assert.equal(ctx.listNativeAnnotations(marked,0)[1].text,'새로운 강조 설명');
 const toDelete=await fresh(raw);
 ctx.updateNativeAnnotation(toDelete,raw,0,1,'delete');
 const deleted=await fresh(await toDelete.save());
 assert.equal(deleted.getPage(0).node.Annots().size(),2);
 assert.equal(ctx.listNativeAnnotations(deleted,0).length,1);
 assert.equal(deleted.getPage(1).node.Annots().size(),1);
 assert.deepEqual(raw,savedRaw,'Original document bytes must be immutable');
 const invalid=await fresh(raw);
 assert.throws(()=>ctx.updateNativeAnnotation(invalid,raw,0,2,'delete'),/안전하게/);
 assert.throws(()=>ctx.updateNativeAnnotation(invalid,raw,0,0,'edit',''),/1~2000/);
 assert.throws(()=>ctx.updateNativeAnnotation(invalid,raw,0,0,'edit','x'.repeat(2001)),/1~2000/);
 assert.throws(()=>ctx.updateNativeAnnotation(invalid,raw,0,0,'edit','abc\u0000def'),/제어문자/);
 assert.throws(()=>ctx.updateNativeAnnotation(invalid,raw,0,0,'move','test'),/지원하지/);
 assert.equal(invalid.getPage(0).node.Annots().size(),3);
 const linked=await fresh(raw);
 const reply=linked.context.obj({Type:'Annot',Subtype:'Text',Rect:[1,1,10,10],
   IRT:linked.getPage(0).node.Annots().get(0),Contents:PDFLib.PDFString.of('reply')});
 linked.getPage(0).node.addAnnot(linked.context.register(reply));
 assert.throws(()=>ctx.updateNativeAnnotation(linked,raw,0,0,'delete'),/연결된/);
 const locked=await fresh(raw);
 locked.context.lookup(locked.getPage(0).node.Annots().get(0)).set(n('F'),PDFLib.PDFNumber.of(64));
 assert(!ctx.listNativeAnnotations(locked,0).some(x=>x.index===0));
 assert.throws(()=>ctx.updateNativeAnnotation(locked,raw,0,0,'edit','blocked'),/안전하게/);
 const popup=await fresh(raw);
 popup.context.lookup(popup.getPage(0).node.Annots().get(0)).set(n('Popup'),popup.context.obj({Type:'Annot'}));
 assert(!ctx.listNativeAnnotations(popup,0).some(x=>x.index===0));
 const form=await fresh(raw);
 form.catalog.set(n('AcroForm'),form.context.obj({Fields:[]}));
 assert.throws(()=>ctx.updateNativeAnnotation(form,raw,0,0,'delete'),/전자서명 또는 양식/);
 const signed=await fresh(raw);
 signed.catalog.set(n('Perms'),signed.context.obj({}));
 assert.throws(()=>ctx.updateNativeAnnotation(signed,raw,0,0,'edit','blocked'),/전자서명 또는 양식/);
 const markerBytes=Uint8Array.from([...raw,...Buffer.from('\n/ByteRange [0 1 2 3]\n')]);
 const markerDoc=await fresh(raw);
 assert.throws(()=>ctx.updateNativeAnnotation(markerDoc,markerBytes,0,0,'edit','blocked'),/전자서명 또는 양식/);
 console.log('PASS: native Text/Highlight Unicode edit+delete, PDF disk-byte roundtrip, unmodified source, foreign annotation preservation, signature/form/reply/locked guards and UI wiring');
})().catch(e=>{console.error(e);process.exitCode=1;});
