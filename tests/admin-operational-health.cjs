const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const {adminApi}=await import('../src/admin-api.mjs');
 const {default:worker}=await import('../src/worker.mjs');
 const base='https://unit.test',url=new URL(base+'/api/admin/health');
 const request=(method='GET')=>new Request(url,{method});
 let queries=0;
 const DB={prepare(sql){
  assert.equal(sql,'SELECT 1 AS ok','health must execute only read-only SELECT');
  queries++;
  return {first:async()=>({ok:1})};
 }};
 let res=await worker.fetch(request(),{DB,ASSETS:{fetch:async()=>new Response('ASSETS')}},{});
 assert.equal(res.status,401,'private status requires administrator authentication');
 assert.equal(queries,0,'unauthorized callers must never query D1');
 const version=require('../package.json').version;
 const deploy='123e4567-e89b-42d3-a456-426614174000';
 res=await adminApi(request(),{DB,CF_VERSION_METADATA:{id:deploy},RELEASE_VERSION:'release-20261031'},url,'administrator');
 assert.equal(res.status,200);
 assert.equal(res.headers.get('cache-control'),'no-store');
 let data=await res.json();
 assert.equal(data.status,'ready');
 assert.deepEqual(data.services,{worker:'responsive',database:'ready'});
 assert.equal(data.version.application,version);
 assert.equal(data.version.deploymentId,deploy);
 assert.equal(data.version.releaseTag,'release-20261031');
 assert(Number.isFinite(Date.parse(data.checkedAt)));
 assert(Number.isFinite(data.probeMs));
 assert.equal(queries,1);
 res=await adminApi(request('POST'),{DB},url,'administrator');
 assert.equal(res.status,405);assert.equal(queries,1);
 const failed={prepare(){return {first:async()=>{throw Error('SECRET_DB_DIAGNOSTIC')}}}};
 res=await adminApi(request(),{DB:failed,RELEASE_VERSION:'invalid white space',CF_VERSION_METADATA:{id:'incorrect'}},url,'administrator');
 assert.equal(res.status,503);data=await res.json();
 assert.equal(data.status,'degraded');
 assert.equal(data.services.worker,'responsive');
 assert.equal(data.services.database,'unavailable');
 assert.equal(data.version.deploymentId,null);
 assert.equal(data.version.releaseTag,null);
 assert(!JSON.stringify(data).includes('SECRET_DB_DIAGNOSTIC'));
 res=await adminApi(request(),{},url,'administrator');
 assert.equal(res.status,503,'missing D1 must be reported as degraded');
 const html=fs.readFileSync('dist/admin/index.html','utf8');
 for(const id of ['healthReload','healthWorker','healthDatabase','healthAppVersion','healthRelease','healthDeployment','operationAlerts'])
  assert(html.includes('id="'+id+'"'),'missing status panel '+id);
 assert(html.includes('/api/admin/health'));
 assert(html.includes('li.textContent=message'),'operator alerts must use text not HTML');
 console.log('PASS: private read-only status, D1 fail closed, verified version labels, operator alert UI');
})().catch(error=>{console.error(error);process.exitCode=1});
